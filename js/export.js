/* ---------- PDF ---------- */
// A4 landscape table document using the standard Helvetica fonts.
// Text is measured with Arial on a canvas, which has Helvetica's widths.
const measureCtx = document.createElement('canvas').getContext('2d');
function textWidth(t, size, bold) {
  measureCtx.font = `${bold ? 'bold ' : ''}${size}px Arial, Helvetica, "Liberation Sans", sans-serif`;
  return measureCtx.measureText(t).width;
}
function wrapText(t, width, size, bold) {
  const out = [];
  for (const para of String(t ?? '').split('\n')) {
    let line = '';
    for (const word of para.split(/\s+/).filter(Boolean)) {
      const tryLine = line ? line + ' ' + word : word;
      if (textWidth(tryLine, size, bold) <= width) { line = tryLine; continue; }
      if (line) out.push(line);
      line = word;
      while (textWidth(line, size, bold) > width && line.length > 1) { // break over-long words
        let k = line.length - 1;
        while (k > 1 && textWidth(line.slice(0, k), size, bold) > width) k--;
        out.push(line.slice(0, k)); line = line.slice(k);
      }
    }
    out.push(line);
  }
  return out.length ? out : [''];
}
// WinAnsi bytes for the standard fonts; anything else becomes "?"
const WIN_ANSI = { '€': 0x80, '‚': 0x82, '„': 0x84, '…': 0x85, '‹': 0x8B, '‘': 0x91, '’': 0x92, '“': 0x93, '”': 0x94,
  '•': 0x95, '–': 0x96, '—': 0x97, '™': 0x99, '›': 0x9B, '₹': null };
function pdfStr(t) {
  let out = '';
  for (const ch of String(t)) {
    let code = ch in WIN_ANSI ? WIN_ANSI[ch] : ch.codePointAt(0);
    if (ch === '₹') { out += 'Rs.'; continue; }
    if (code == null || code > 255) code = 63;
    if (code === 40 || code === 41 || code === 92) out += '\\' + String.fromCharCode(code);
    else if (code < 32 || code > 126) out += '\\' + code.toString(8).padStart(3, '0');
    else out += String.fromCharCode(code);
  }
  return out;
}

function exportPdf(o) {
  const W = 842, H = 595, M = 28, BOTTOM = M + 16;
  const pages = [];
  let ops, y;
  const fmt = n => (Math.round(n * 100) / 100).toString();
  const text = (s, x, yy, size, bold, gray) =>
    ops.push(`${gray ? '0.4 g ' : ''}BT /${bold ? 'F2' : 'F1'} ${fmt(size)} Tf ${fmt(x)} ${fmt(yy)} Td (${pdfStr(s)}) Tj ET${gray ? ' 0 g' : ''}`);
  const rect = (x, yy, w, h, g) => ops.push(`${g} g ${fmt(x)} ${fmt(yy)} ${fmt(w)} ${fmt(h)} re f 0 g`);
  const hline = (x1, x2, yy, wgt = 0.3) => ops.push(`0.7 G ${wgt} w ${fmt(x1)} ${fmt(yy)} m ${fmt(x2)} ${fmt(yy)} l S`);
  function newPage() { ops = []; pages.push(ops); y = H - M; }

  // cols: [{h, w, align}] widths in points summing to the page width
  function table(heading, cols, rows, size) {
    const lh = size * 1.22, pad = 2.5;
    const xs = []; let x = M;
    for (const c of cols) { xs.push(x); x += c.w; }
    const right = x;
    function drawHeader() {
      const lines = cols.map(c => wrapText(c.h, c.w - 2 * pad, size, true));
      const h = Math.max(...lines.map(l => l.length)) * lh + 2 * pad;
      rect(M, y - h, right - M, h, 0.88);
      lines.forEach((ls, i) => ls.forEach((t, k) => {
        const tw = textWidth(t, size, true);
        const tx = cols[i].align === 'r' ? xs[i] + cols[i].w - pad - tw : xs[i] + pad;
        text(t, tx, y - pad - size * 0.85 - k * lh, size, true);
      }));
      y -= h;
    }
    function ensure(h) {
      if (y - h < BOTTOM) { newPage(); text(heading + ' (continued)', M, y - 10, 9, true); y -= 16; drawHeader(); }
    }
    if (y - 60 < BOTTOM) newPage();
    text(heading, M, y - 11, 11, true); y -= 18;
    drawHeader();
    for (const r of rows) {
      const fs = r.small ? size - 0.8 : size;
      if (r.span != null) { // one cell across the row (group heading / total label)
        const spanW = (r.last != null ? xs[cols.length - 1] : right) - M;
        const lines = wrapText(r.span, spanW - 2 * pad - (r.indent || 0), fs, true);
        const h = lines.length * lh + 2 * pad;
        ensure(h);
        if (r.fill) rect(M, y - h, right - M, h, r.fill);
        lines.forEach((t, k) => {
          const tw = textWidth(t, fs, true);
          const tx = r.align === 'r' ? M + spanW - pad - tw : M + pad + (r.indent || 0);
          text(t, tx, y - pad - fs * 0.85 - k * lh, fs, true);
        });
        if (r.last != null) {
          const tw = textWidth(r.last, fs, true);
          text(r.last, right - pad - tw, y - pad - fs * 0.85, fs, true);
        }
        y -= h;
        hline(M, right, y, r.rule ? 0.8 : 0.3);
        continue;
      }
      const b = !!r.bold;
      const lines = r.cells.map((t, i) => wrapText(t, cols[i].w - 2 * pad, fs, b));
      const h = Math.max(...lines.map(l => l.length)) * lh + 2 * pad;
      ensure(h);
      lines.forEach((ls, i) => ls.forEach((t, k) => {
        const tw = textWidth(t, fs, b);
        const tx = cols[i].align === 'r' ? xs[i] + cols[i].w - pad - tw : xs[i] + pad;
        text(t, tx, y - pad - fs * 0.85 - k * lh, fs, b, r.small);
      }));
      y -= h;
      if (!r.small) hline(M, right, y, r.rule ? 0.8 : 0.3);
    }
    y -= 14;
  }

  newPage();
  text(project.name || 'BOQ', M, y - 14, 15, true);
  text(exportMeta().join('   ·   '), M, y - 29, 8, false, true);
  y -= 42;

  const usable = W - 2 * M;
  if (o.sheet) {
    const spec = [['#', 22, 'r'], ['Service No', 44], ['Short Text', 118], ['Description', 118], ['No', 34, 'r'], ['L', 38, 'r'],
      ['B', 34, 'r'], ['H/D', 44, 'r'], ['Qty', 48, 'r'], ['Unit', 26], ['Price', 56, 'r'], ['Amount', 64, 'r'], ['PO Item', 54], ['Asset', 0]];
    const used = spec.reduce((t, c) => t + c[1], 0);
    const cols = spec.map(([h, w, a]) => ({ h, w: w || usable - used, align: a }));
    const rows = sheetRows().map(r => ({ cells: [String(r.n), r.code, r.short, r.desc, r.dims[0], r.dims[1], r.dims[2],
      r.dims[3] + (r.hdSection ? '\n' + r.hdSection : ''), r.qty, r.unit, r.price, r.amount, r.po, r.asset] }));
    const total = Array(cols.length).fill('');
    total[10] = 'Total'; total[11] = fmtMoney(sheetTotal());
    rows.push({ cells: total, bold: true, rule: true });
    table('Measurement sheet', cols, rows, 7);
  }
  if (o.report) {
    const spec = [['Sl', 26, 'r'], ['Service No', 60], ['Short Text', 0], ['Unit', 40], ['Qty', 80, 'r'], ['Price', 80, 'r'], ['Amount', 90, 'r']];
    const used = spec.reduce((t, c) => t + c[1], 0);
    const cols = spec.map(([h, w, a]) => ({ h, w: w || usable - used, align: a }));
    const rows = [];
    for (const r of reportRows(o.levels, o.hideZero, o.detail)) {
      if (r.type === 'group') rows.push({ span: `${r.label}: ${r.name}`, fill: r.depth ? 0.96 : 0.92, indent: r.depth * 12 });
      else if (r.type === 'item') {
        const t = itemText(r.it);
        rows.push({ cells: [String(r.sl), r.it.code, t.short, t.unit, t.qty, t.price, t.amount] });
      } else if (r.type === 'detail') rows.push({ small: true, cells: ['', '#' + r.ln.n, r.ln.desc, '', fmtQty(r.ln.qty, r.it.uf), '', ''] });
      else if (r.type === 'subtotal') rows.push({ span: `Total ${r.name}`, align: 'r', last: fmtMoney(r.amount), rule: true });
      else rows.push({ span: 'Grand total', align: 'r', last: fmtMoney(r.amount), fill: 0.88, rule: true });
    }
    table(`Report — consolidated by ${groupingName(o.levels).replace(/›/g, '>')}`, cols, rows, 8);
  }

  // assemble: page numbers, objects, xref
  const n = pages.length;
  pages.forEach((p, i) => {
    ops = p;
    text(`${project.name || 'BOQ'}`, M, M - 6, 7, false, true);
    const pg = `Page ${i + 1} of ${n}`;
    text(pg, W - M - textWidth(pg, 7, false), M - 6, 7, false, true);
  });
  const objs = [];
  const add = s => { objs.push(s); return objs.length; };
  const catalog = add(null), pagesObj = add(null);
  const f1 = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>');
  const f2 = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>');
  const kids = [];
  for (const p of pages) {
    const content = p.join('\n');
    const c = add(`<< /Length ${content.length} >>\nstream\n${content}\nendstream`);
    kids.push(add(`<< /Type /Page /Parent ${pagesObj} 0 R /MediaBox [0 0 ${W} ${H}] /Contents ${c} 0 R ` +
      `/Resources << /Font << /F1 ${f1} 0 R /F2 ${f2} 0 R >> >> >>`));
  }
  objs[catalog - 1] = `<< /Type /Catalog /Pages ${pagesObj} 0 R >>`;
  objs[pagesObj - 1] = `<< /Type /Pages /Kids [${kids.map(k => k + ' 0 R').join(' ')}] /Count ${kids.length} >>`;
  const info = add(`<< /Title (${pdfStr(project.name || 'BOQ')}) /Producer (${pdfStr(APP_ID)}) >>`);
  let out = '%PDF-1.4\n';
  const offsets = objs.map((o2, i) => { const off = out.length; out += `${i + 1} 0 obj\n${o2}\nendobj\n`; return off; });
  const xref = out.length;
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + offsets.map(x => String(x).padStart(10, '0') + ' 00000 n \n').join('');
  out += `trailer\n<< /Size ${objs.length + 1} /Root ${catalog} 0 R /Info ${info} 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return new Blob([out], { type: 'application/pdf' });
}

/* ---------- Excel (.xlsx) ---------- */
// Cells: null | number | string | { v, f (formula), s (style), t: 's' for text }
// Styles: 0 normal, 1 bold, 2 #,##0.00, 3 #,##0.000, 4 bold #,##0.00, 5 title,
// 6 header, 7 group row, 8 grey detail, 9 grey detail #,##0.000, 10 general number
const XS = { normal: 0, bold: 1, money: 2, qty3: 3, boldMoney: 4, title: 5, head: 6, group: 7, detail: 8, detailQty: 9, gen: 10 };
const qtyStyle = uf => uf.min === 0 ? XS.gen : uf.dp === 2 ? XS.money : XS.qty3;
const colName = i => { let s = ''; i++; while (i) { const m = (i - 1) % 26; s = String.fromCharCode(65 + m) + s; i = (i - m - 1) / 26; } return s; };
const xmlEsc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]))
  .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '');

function sheetXml({ cols, rows, merges = [], freeze = 0 }) {
  let x = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n' +
    '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">' +
    '<sheetPr><pageSetUpPr fitToPage="1"/></sheetPr>';
  if (freeze) x += `<sheetViews><sheetView workbookViewId="0"><pane ySplit="${freeze}" topLeftCell="A${freeze + 1}" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>`;
  x += '<cols>' + cols.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('') + '</cols><sheetData>';
  rows.forEach((row, ri) => {
    if (!row) return;
    x += `<row r="${ri + 1}">`;
    row.forEach((cell, ci) => {
      if (cell == null || cell === '') return;
      const c = typeof cell === 'object' ? cell : { v: cell };
      const ref = colName(ci) + (ri + 1), s = c.s ? ` s="${c.s}"` : '';
      if (c.f) x += `<c r="${ref}"${s}><f>${xmlEsc(c.f)}</f>${typeof c.v === 'number' && isFinite(c.v) ? `<v>${c.v}</v>` : ''}</c>`;
      else if (typeof c.v === 'number' && c.t !== 's') x += `<c r="${ref}"${s}><v>${c.v}</v></c>`;
      else x += `<c r="${ref}"${s} t="inlineStr"><is><t xml:space="preserve">${xmlEsc(c.v)}</t></is></c>`;
    });
    x += '</row>';
  });
  x += '</sheetData>';
  if (merges.length) x += `<mergeCells count="${merges.length}">` + merges.map(m => `<mergeCell ref="${m}"/>`).join('') + '</mergeCells>';
  x += '<pageMargins left="0.4" right="0.4" top="0.5" bottom="0.5" header="0.3" footer="0.3"/>' +
    '<pageSetup paperSize="9" orientation="landscape" fitToWidth="1" fitToHeight="0"/></worksheet>';
  return x;
}
