function exportXlsx(o) {
  const sheets = [];
  const codeCell = code => /^\d{1,15}$/.test(code || '') ? Number(code) : (code || '');
  const head = [[{ v: project.name || 'BOQ', s: XS.title }], [{ v: exportMeta().join('   ·   '), s: XS.detail }], null];
  if (o.sheet) {
    const rows = [...head];
    rows.push(['#', 'Service No', 'Short Text', 'Description', 'No', 'L', 'B', 'H/D', 'Qty', 'Unit', 'Price', 'Amount', 'PO Item', 'Asset', 'H/D section']
      .map(v => ({ v, s: XS.head })));
    const first = rows.length + 1;
    for (const r of sheetRows()) {
      const R = rows.length + 1, l = r.line, c = r.c;
      const dims = DIMS.map(d => {
        const e = evalExpr(l[d]);
        if (e.error) return { v: l[d], t: 's' };
        if (e.value === null) return null;
        return isPlainNumber(l[d]) ? { v: e.value, s: XS.gen } : { f: excelFormula(e.ast), v: e.value, s: XS.gen };
      });
      const qty = c.err ? { v: '#ERR', t: 's' }
        : { f: `ROUND(PRODUCT(E${R}:H${R}),${c.uf.dp})`, v: c.qty, s: qtyStyle(c.uf) };
      rows.push([r.n, codeCell(r.code), r.short, r.desc, ...dims, qty, r.unit,
        c.sor ? { v: c.price, s: XS.money } : (c.look ? '—' : null),
        c.sor && !c.err ? { f: `ROUND(I${R}*K${R},2)`, v: c.amount, s: XS.money } : null,
        r.po, r.asset, r.hdSection]);
    }
    const last = rows.length;
    rows.push([null, null, null, null, null, null, null, null, null, null, { v: 'Total', s: XS.bold },
      { f: `SUM(L${first}:L${last})`, v: sheetTotal(), s: XS.boldMoney }]);
    sheets.push({ name: 'Measurement', xml: sheetXml({ cols: [5, 11, 34, 34, 8, 8, 8, 9, 11, 6, 11, 13, 12, 18, 14], rows, freeze: 4 }) });
  }
  if (o.report) {
    const rows = [...head, [{ v: `Consolidated by ${groupingName(o.levels)}`, s: XS.bold }]];
    rows.push(['Sl', 'Service No', 'Short Text', 'Unit', 'Qty', 'Price', 'Amount'].map(v => ({ v, s: XS.head })));
    const merges = [];
    for (const r of reportRows(o.levels, o.hideZero, o.detail)) {
      const R = rows.length + 1;
      if (r.type === 'group') {
        rows.push([{ v: `${'    '.repeat(r.depth)}${r.label}: ${r.name}`, s: XS.group }, ...Array(6).fill({ v: '', s: XS.group })]);
        merges.push(`A${R}:G${R}`);
      } else if (r.type === 'item') {
        const it = r.it, t = itemText(it);
        rows.push([r.sl, codeCell(it.code), t.short, t.unit,
          it.err ? '#ERR' : { v: it.qty, s: qtyStyle(it.uf) },
          it.sor ? { v: it.price, s: XS.money } : (it.look ? '—' : null),
          it.sor && !it.err ? { f: `ROUND(E${R}*F${R},2)`, v: it.amount, s: XS.money } : null]);
      } else if (r.type === 'detail') {
        rows.push([null, { v: '#' + r.ln.n, s: XS.detail }, { v: r.ln.desc, s: XS.detail }, null,
          { v: r.ln.qty, s: XS.detailQty }]);
      } else {
        rows.push([null, null, { v: r.type === 'grand' ? 'Grand total' : `Total ${r.name}`, s: XS.bold }, null, null, null,
          { v: r.amount, s: XS.boldMoney }]);
      }
    }
    sheets.push({ name: 'Report', xml: sheetXml({ cols: [5, 11, 48, 7, 12, 12, 15], rows, merges, freeze: 5 }) });
  }
  const files = [
    ['[Content_Types].xml', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n' +
      '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">' +
      '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>' +
      '<Default Extension="xml" ContentType="application/xml"/>' +
      '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>' +
      '<Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>' +
      sheets.map((s, i) => `<Override PartName="/xl/worksheets/sheet${i + 1}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>`).join('') +
      '</Types>'],
    ['_rels/.rels', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n' +
      '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">' +
      '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>'],
    ['xl/workbook.xml', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n' +
      '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets>' +
      sheets.map((s, i) => `<sheet name="${s.name}" sheetId="${i + 1}" r:id="rId${i + 1}"/>`).join('') +
      '</sheets><calcPr calcId="191029" fullCalcOnLoad="1"/></workbook>'],
    ['xl/_rels/workbook.xml.rels', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n' +
      '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">' +
      sheets.map((s, i) => `<Relationship Id="rId${i + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet${i + 1}.xml"/>`).join('') +
      `<Relationship Id="rId${sheets.length + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/></Relationships>`],
    ['xl/styles.xml', STYLES_XML],
    ...sheets.map((s, i) => [`xl/worksheets/sheet${i + 1}.xml`, s.xml]),
  ];
  return new Blob([zipStore(files)], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
}

// Minimal ZIP writer (stored, no compression) — all an .xlsx needs
const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; t[n] = c >>> 0; }
  return t;
})();
function crc32(b) { let c = 0xFFFFFFFF; for (let i = 0; i < b.length; i++) c = CRC_TABLE[(c ^ b[i]) & 0xFF] ^ (c >>> 8); return (c ^ 0xFFFFFFFF) >>> 0; }
function zipStore(files) {
  const enc = new TextEncoder();
  const entries = files.map(([name, text]) => ({ name: enc.encode(name), data: enc.encode(text) }));
  entries.forEach(e => { e.crc = crc32(e.data); });
  const size = entries.reduce((t, e) => t + 30 + e.name.length + e.data.length + 46 + e.name.length, 22);
  const buf = new Uint8Array(size), dv = new DataView(buf.buffer);
  let p = 0;
  const u16 = v => { dv.setUint16(p, v, true); p += 2; }, u32 = v => { dv.setUint32(p, v, true); p += 4; };
  for (const e of entries) {
    e.offset = p;
    u32(0x04034B50); u16(20); u16(0x0800); u16(0); u16(0); u16(0x21);
    u32(e.crc); u32(e.data.length); u32(e.data.length); u16(e.name.length); u16(0);
    buf.set(e.name, p); p += e.name.length; buf.set(e.data, p); p += e.data.length;
  }
  const cd = p;
  for (const e of entries) {
    u32(0x02014B50); u16(20); u16(20); u16(0x0800); u16(0); u16(0); u16(0x21);
    u32(e.crc); u32(e.data.length); u32(e.data.length); u16(e.name.length); u16(0); u16(0); u16(0); u16(0); u32(0); u32(e.offset);
    buf.set(e.name, p); p += e.name.length;
  }
  const cdSize = p - cd;
  u32(0x06054B50); u16(0); u16(0); u16(entries.length); u16(entries.length); u32(cdSize); u32(cd); u16(0);
  return buf;
}
