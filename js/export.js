// Measurement sheet as display rows (shared by all three formats)
function sheetRows() {
  return project.lines.map((l, i) => {
    const c = compute(l);
    const dims = DIMS.map(d => {
      const r = evalExpr(l[d]);
      return r.error ? l[d] : r.value === null ? '' : fmtDim(r.value, c.uf);
    });
    return {
      n: i + 1, line: l, c, code: l.code,
      short: c.info ? c.info.short : (l.code ? 'Not in SOR' : ''),
      desc: l.desc, dims, hdSection: l.hdSection,
      qty: l.code || c.qty ? fmtQty(c.qty, c.uf) : '',
      unit: c.info?.unit || l.ref?.unit || '',
      price: c.sor ? fmtMoney(c.price) : (c.look ? '—' : ''),
      amount: c.sor ? fmtMoney(c.amount) : '',
      po: l.poItem, asset: l.asset,
    };
  });
}
const sheetTotal = () => roundTo(project.lines.reduce((t, l) => t + compute(l).amount, 0), 2);

// Report as a flat list of rows: group headings, items, measurement lines,
// subtotals and the grand total
function reportRows(levels, hideZero, detail) {
  const root = buildReport(levels), rows = [];
  function items(node, path) {
    let sl = 0;
    for (const it of visibleItems(node, hideZero)) {
      rows.push({ type: 'item', sl: ++sl, it, path });
      if (detail) for (const ln of it.lines) rows.push({ type: 'detail', it, ln });
    }
  }
  function group(node, depth, path) {
    for (const kid of node.kids.values()) {
      if (!hasVisible(kid, hideZero)) continue;
      const p = [...path, kid.name];
      rows.push({ type: 'group', depth, label: FIELD_LABEL[kid.field], name: kid.name });
      if (kid.kids.size) group(kid, depth + 1, p); else items(kid, p);
      rows.push({ type: 'subtotal', depth, name: kid.name, amount: kid.amount });
    }
  }
  if (levels.length) group(root, 0, []); else items(root, []);
  rows.push({ type: 'grand', amount: root.amount });
  return rows;
}
function itemText(it) {
  const noRate = it.look && !it.sor;
  return {
    short: it.info ? it.info.short : 'Not in SOR',
    unit: it.info?.unit || '',
    qty: it.err ? '#ERR' : fmtQty(it.qty, it.uf),
    price: noRate ? '—' : it.sor ? fmtMoney(it.price) : '',
    amount: it.sor ? fmtMoney(it.amount) : '',
  };
}
const groupingName = levels => levels.map(f => FIELD_LABEL[f]).join(' › ') || 'Service No (abstract)';
function exportMeta() {
  return [
    project.state ? `State: ${project.state}` : '',
    project.date ? `Rates as on ${fmtDate(project.date)}` : 'No rate date set',
    discountFrac() ? `Discount ${project.discount}%` : '',
    `SOR: ${SOR.source}`,
    `Generated by ${APP_ID} on ${new Date().toLocaleDateString('en-GB').replace(/\//g, '-')}`,
  ].filter(Boolean);
}

